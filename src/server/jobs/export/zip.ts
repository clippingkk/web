import { crc32, deflateRawSync, inflateRawSync } from 'node:zlib'

export type ZipEntry = {
  name: string
  data: Buffer
}

/**
 * A deflated ZIP of the given files. Paths are stored as given, so callers
 * pass vault-relative names such as `clippingkk/Title.md`.
 */
export function zipFiles(
  files: readonly { name: string; data: Buffer | string }[]
): Buffer {
  const locals: Buffer[] = []
  const centrals: Buffer[] = []
  let offset = 0
  for (const file of files) {
    const name = Buffer.from(file.name, 'utf8')
    const data =
      typeof file.data === 'string' ? Buffer.from(file.data) : file.data
    const compressed = deflateRawSync(data)
    const checksum = crc32(data) >>> 0
    const local = Buffer.alloc(30)
    local.writeUInt32LE(0x04034b50, 0)
    local.writeUInt16LE(20, 4)
    local.writeUInt16LE(0, 6)
    local.writeUInt16LE(8, 8)
    local.writeUInt16LE(0, 10)
    local.writeUInt16LE(0, 12)
    local.writeUInt32LE(checksum, 14)
    local.writeUInt32LE(compressed.length, 18)
    local.writeUInt32LE(data.length, 22)
    local.writeUInt16LE(name.length, 26)
    local.writeUInt16LE(0, 28)
    const record = Buffer.concat([local, name, compressed])
    locals.push(record)

    const central = Buffer.alloc(46)
    central.writeUInt32LE(0x02014b50, 0)
    central.writeUInt16LE(20, 4)
    central.writeUInt16LE(20, 6)
    central.writeUInt16LE(0, 8)
    central.writeUInt16LE(8, 10)
    central.writeUInt16LE(0, 12)
    central.writeUInt16LE(0, 14)
    central.writeUInt32LE(checksum, 16)
    central.writeUInt32LE(compressed.length, 20)
    central.writeUInt32LE(data.length, 24)
    central.writeUInt16LE(name.length, 28)
    central.writeUInt16LE(0, 30)
    central.writeUInt16LE(0, 32)
    central.writeUInt16LE(0, 34)
    central.writeUInt16LE(0, 36)
    central.writeUInt32LE(0, 38)
    central.writeUInt32LE(offset, 42)
    centrals.push(Buffer.concat([central, name]))
    offset += record.length
  }
  const directory = Buffer.concat(centrals)
  const end = Buffer.alloc(22)
  end.writeUInt32LE(0x06054b50, 0)
  end.writeUInt16LE(0, 4)
  end.writeUInt16LE(0, 6)
  end.writeUInt16LE(files.length, 8)
  end.writeUInt16LE(files.length, 10)
  end.writeUInt32LE(directory.length, 12)
  end.writeUInt32LE(offset, 16)
  end.writeUInt16LE(0, 20)
  return Buffer.concat([...locals, directory, end])
}

/** Reads entries written by `zipFiles`. Used to check vault archives. */
export function readZip(archive: Buffer): ZipEntry[] {
  const entries: ZipEntry[] = []
  let offset = 0
  while (offset + 30 <= archive.length) {
    const signature = archive.readUInt32LE(offset)
    if (signature !== 0x04034b50) break
    const method = archive.readUInt16LE(offset + 8)
    const compressedSize = archive.readUInt32LE(offset + 18)
    const nameLength = archive.readUInt16LE(offset + 26)
    const extraLength = archive.readUInt16LE(offset + 28)
    const nameStart = offset + 30
    const dataStart = nameStart + nameLength + extraLength
    const name = archive.toString('utf8', nameStart, nameStart + nameLength)
    const compressed = archive.subarray(dataStart, dataStart + compressedSize)
    const data =
      method === 0 ? Buffer.from(compressed) : inflateRawSync(compressed)
    entries.push({ name, data })
    offset = dataStart + compressedSize
  }
  return entries
}
